"""Bridge to the compiled HEM-Elite-Rack plug-ins (tools/rack_render -> hem_rack_render.exe).

The catalog is generated by the build itself (`hem_rack_render --list`), so plug-in names and
parameter ids always match the code that will run. Nothing here is typed in by hand.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

# Plug-ins offered to Claude by default: restoration, EQ, de-essing, transients, bus glue, limiting.
# Names that are not in the catalog are skipped (with a note), never guessed.
DEFAULT_OFFER = ("SURGEON", "THE CLEANER", "SILENCER", "OMERTA", "KNOCKOUT", "THE FAMILY", "LOCKDOWN")


def load_catalog(path: Path) -> dict:
    cat = json.loads(Path(path).read_text(encoding="utf-8"))
    if cat.get("format") != "hem-rack-catalog/1":
        raise SystemExit(f"{path} is not a hem_rack_render catalog")
    cat["by_name"] = {p["name"]: p for p in cat["plugins"]}
    return cat


def generate_catalog(exe: Path, out: Path) -> dict:
    r = subprocess.run([str(exe), "--list", "--out", str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"hem_rack_render --list failed ({r.returncode}): {r.stderr.strip()}")
    return load_catalog(out)


def offer(catalog: dict, names: list[str] | None) -> tuple[list[dict], list[str]]:
    """The plug-ins (with their controls) put in front of Claude, and the names that were not found."""
    wanted = list(names) if names else list(DEFAULT_OFFER)
    found, missing = [], []
    for n in wanted:
        p = catalog["by_name"].get(n)
        if p is None:
            missing.append(n)
            continue
        found.append({"name": p["name"], "suite": p["suite"], "blurb": p["blurb"], "latency48k": p["latency48k"],
                      "controls": [{k: q[k] for k in ("id", "name", "unit", "min", "max", "default", "taper")} |
                                   ({"choices": q["choices"]} if "choices" in q else {})
                                   for q in p["params"] if not q.get("stored")]})
    return found, missing


def write_chain(steps: list[dict], path: Path) -> None:
    lines = ["# written by suno_repair; run with: hem_rack_render --chain this.hemchain --in in.wav --out out.wav"]
    for st in steps:
        lines.append(f"plugin {st['plugin']}")
        for s in st.get("settings", []):
            lines.append(f"set {s['id']} {float(s['value']):.9g}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_chain(exe: Path, chain: Path, wav_in: Path, wav_out: Path, report: Path, tempo: float | None = None) -> dict:
    cmd = [str(exe), "--chain", str(chain), "--in", str(wav_in), "--out", str(wav_out), "--report", str(report)]
    if tempo:
        cmd += ["--tempo", f"{tempo:.3f}"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode not in (0, 4):
        raise SystemExit(f"hem_rack_render failed ({r.returncode}) on {wav_in.name}: {r.stderr.strip()}")
    rep = json.loads(report.read_text(encoding="utf-8"))
    rep["exit_code"] = r.returncode
    return rep
